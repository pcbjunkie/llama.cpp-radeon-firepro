#!/usr/bin/env python3
# local: build comm_wait SPIR-V with Nontemporal flag loads (slc on GCN, L2 bypass), emit a C header.
# usage: local-gen-comm-wait.py <glslc> <shader.comp> <out.h> [array name]
import re, subprocess, sys, tempfile, os
glslc, src, out = sys.argv[1:4]
name = sys.argv[4] if len(sys.argv) > 4 else "local_comm_wait_spv"
with tempfile.TemporaryDirectory() as d:
    asm = os.path.join(d, "a.spvasm")
    spv = os.path.join(d, "a.spv")
    subprocess.check_call([glslc, "--target-env=vulkan1.2", "-fshader-stage=compute", "-S", "-o", asm, src])
    lines = open(asm).read().split("\n")
    chains = set()
    for l in lines:
        m = re.match(r"\s*%(\w+) = OpAccessChain %_ptr_StorageBuffer_uint %_+\d* ", l + " ")
        if m:
            chains.add(m.group(1))
    n = 0
    for i, l in enumerate(lines):
        m = re.match(r"(\s*%\w+ = OpLoad %uint %(\w+))\s*$", l)
        if m and m.group(2) in chains:
            lines[i] = m.group(1) + " Volatile|Nontemporal"
            n += 1
    assert n >= 0, n
    open(asm, "w").write("\n".join(lines))
    subprocess.check_call(["spirv-as", "--target-env", "vulkan1.2", "-o", spv, asm])
    subprocess.check_call(["spirv-val", "--target-env", "vulkan1.2", spv])
    data = open(spv, "rb").read()
with open(out, "w") as f:
    f.write("// generated by local-gen-comm-wait.py, do not edit\n#pragma once\n#include <cstdint>\n")
    f.write("static const unsigned char %s[] = {\n" % name)
    for i in range(0, len(data), 16):
        f.write("    " + ", ".join("0x%02x" % b for b in data[i:i+16]) + ",\n")
    f.write("};\n")
print("patched loads:", n, "bytes:", len(data))
